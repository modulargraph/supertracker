import Foundation
import Darwin

@main
struct AudioExportTransactionTests {
    struct TestFailure: Error, CustomStringConvertible { let description: String }
    static let fm = FileManager.default

    static func require(_ condition: @autoclosure () throws -> Bool, _ message: String) throws {
        if try !condition() { throw TestFailure(description: message) }
    }
    static func rejects(_ message: String, _ body: () throws -> Void) throws {
        do { try body() } catch { return }
        throw TestFailure(description: "Expected rejection: " + message)
    }
    static func bytes(_ value: String, to url: URL) throws { try Data(value.utf8).write(to: url) }
    static func content(_ url: URL) throws -> String { String(decoding: try Data(contentsOf: url), as: UTF8.self) }
    static func directory(_ parent: URL, _ name: String) throws -> URL {
        let url = parent.appendingPathComponent(name, isDirectory: true)
        try fm.createDirectory(at: url, withIntermediateDirectories: false)
        return url
    }
    static func stagingGone(_ tx: AudioExportTransaction) throws {
        try require(!fm.fileExists(atPath: tx.sourcesDirectoryURL.deletingLastPathComponent().path), "Private root leaked")
    }

    static func main() throws {
        let output = URL(fileURLWithPath: CommandLine.arguments.dropFirst().first ?? "test-output/audio-export-transaction")
            .standardizedFileURL.resolvingSymlinksInPath()
        try fm.createDirectory(at: output, withIntermediateDirectories: true)
        let root = try directory(output, "fixtures-" + UUID().uuidString)
        var checks: [String] = []
        let began = Date()
        func report(error: String? = nil) throws {
            var result: [String: Any] = ["passed": error == nil, "checks": checks,
                "fixtureRoot": root.path, "elapsedSeconds": Date().timeIntervalSince(began),
                "scope": "Pure filesystem only; generated bytes, no audio/Host/device/plugin execution"]
            if let error { result["error"] = error }
            let data = try JSONSerialization.data(withJSONObject: result, options: [.prettyPrinted, .sortedKeys])
            try data.write(to: output.appendingPathComponent("report.json"), options: .atomic)
        }
        func test(_ name: String, _ body: (URL) throws -> Void) throws {
            let folder = try directory(root, String(format: "%02d-", checks.count + 1) + name)
            try body(folder); checks.append(name); try report()
            print("PASS " + name)
            fflush(stdout)
        }
        do {
            try test("single-file-atomic-replace") { folder in
                let final = folder.appendingPathComponent("authorized.wav")
                try bytes("original", to: final)
                let tx = try AudioExportTransaction(destinationURL: final, kind: .file)
                let entry = try tx.register(filename: "private.wav")
                try require(entry.finalURL == final && entry.sourceURL.pathExtension == "caf", "Entry path contract")
                try require(entry.destinationURL != final, "Conversion targeted public destination")
                try bytes("source-only", to: entry.sourceURL)
                try bytes("verified-new-wave", to: entry.destinationURL)
                try require(content(final) == "original", "Destination changed before publish")
                try require(tx.publish() == [final], "Wrong published paths")
                try require(content(final) == "verified-new-wave", "New file not atomically published")
                try require(tx.cleanupError == nil, "Successful cleanup error")
                try tx.discard(); try tx.discard(); try stagingGone(tx)
                try require(content(final) == "verified-new-wave", "Discard removed published file")
                try rejects("second publication") { _ = try tx.publish() }
                try rejects("register after publication") { _ = try tx.register(filename: "later.wav") }
            }
            try test("cancel-and-incomplete-preserve-original") { folder in
                let final = folder.appendingPathComponent("existing.wav")
                try bytes("keep-original", to: final)
                let cancelled = try AudioExportTransaction(destinationURL: final, kind: .file)
                let entry = try cancelled.register(filename: "one.wav")
                try bytes("partial-source", to: entry.sourceURL)
                try bytes("converted-but-cancelled", to: entry.destinationURL)
                try cancelled.discard(); try cancelled.discard()
                try stagingGone(cancelled)
                try require(content(final) == "keep-original", "Cancellation overwrote destination")
                let failed = try AudioExportTransaction(destinationURL: final, kind: .file)
                _ = try failed.register(filename: "missing.wav")
                try rejects("missing converted file") { _ = try failed.publish() }
                try require(content(final) == "keep-original", "Conversion failure overwrote destination")
                try failed.discard(); try stagingGone(failed)
            }
            try test("whole-stems-empty-and-absent") { folder in
                for initiallyExists in [false, true] {
                    let target = folder.appendingPathComponent(initiallyExists ? "reserved" : "new", isDirectory: true)
                    if initiallyExists { try fm.createDirectory(at: target, withIntermediateDirectories: false) }
                    let tx = try AudioExportTransaction(destinationURL: target, kind: .stems)
                    let kick = try tx.register(filename: "01 Kick.wav")
                    let bus = try tx.register(filename: "02 Bus.wav")
                    try bytes("kick", to: kick.destinationURL)
                    try rejects("partial stems") { _ = try tx.publish() }
                    if initiallyExists {
                        try require(fm.contentsOfDirectory(atPath: target.path).isEmpty, "Partially published reserved stems")
                    } else { try require(!fm.fileExists(atPath: target.path), "Partially published absent stems") }
                    try bytes("bus", to: bus.destinationURL)
                    try require(tx.publish() == [kick.finalURL, bus.finalURL], "Stem path order")
                    try require(Set(fm.contentsOfDirectory(atPath: target.path)) == ["01 Kick.wav", "02 Bus.wav"], "Incomplete directory publication")
                    try require(content(kick.finalURL) == "kick" && content(bus.finalURL) == "bus", "Stem bytes changed")
                    try tx.discard(); try stagingGone(tx)
                    try require(content(bus.finalURL) == "bus", "Discard deleted committed stems")
                }
            }
            try test("destination-shape-validation") { folder in
                let nonempty = try directory(folder, "nonempty")
                try bytes("unrelated", to: nonempty.appendingPathComponent("user.txt"))
                try rejects("nonempty initial stems") { _ = try AudioExportTransaction(destinationURL: nonempty, kind: .stems) }
                try rejects("directory for file") { _ = try AudioExportTransaction(destinationURL: nonempty, kind: .file) }
                let file = folder.appendingPathComponent("file.wav"); try bytes("file", to: file)
                try rejects("file for stems") { _ = try AudioExportTransaction(destinationURL: file, kind: .stems) }
                try rejects("missing parent") { _ = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("missing/out.wav"), kind: .file) }
                try rejects("remote URL") { _ = try AudioExportTransaction(destinationURL: URL(string: "https://example.test/a.wav")!, kind: .file) }
                try require(content(nonempty.appendingPathComponent("user.txt")) == "unrelated", "Invalid init altered user data")
                try require(!fm.contentsOfDirectory(atPath: folder.path).contains(where: { $0.hasPrefix(".supertracker-export-") }), "Invalid init leaked staging")
            }
            try test("changed-targets-refuse-commit") { folder in
                for change in ["appeared", "replaced", "in-place", "removed"] {
                    let target = folder.appendingPathComponent(change + ".wav")
                    if change != "appeared" { try bytes("old", to: target) }
                    let tx = try AudioExportTransaction(destinationURL: target, kind: .file)
                    let entry = try tx.register(filename: "ready.wav"); try bytes("ours", to: entry.destinationURL)
                    if change == "removed" { try fm.removeItem(at: target) }
                    else if change == "replaced" {
                        try fm.removeItem(at: target); try bytes("new-owner", to: target)
                    } else {
                        try bytes("new-owner", to: target)
                        if change == "in-place" { try fm.setAttributes([.modificationDate: Date(timeIntervalSince1970: 12345)], ofItemAtPath: target.path) }
                    }
                    try rejects(change) { _ = try tx.publish() }
                    if change == "removed" { try require(!fm.fileExists(atPath: target.path), "Recreated removed target") }
                    else { try require(content(target) == "new-owner", "Replaced changed target") }
                    try tx.discard()
                }
                let target = try directory(folder, "now-nonempty")
                let tx = try AudioExportTransaction(destinationURL: target, kind: .stems)
                let entry = try tx.register(filename: "ready.wav"); try bytes("ours", to: entry.destinationURL)
                try bytes("foreign", to: target.appendingPathComponent("foreign.txt"))
                try rejects("reserved directory became nonempty") { _ = try tx.publish() }
                try require(content(target.appendingPathComponent("foreign.txt")) == "foreign", "Removed new directory content")
                try tx.discard()
            }
            try test("leaf-and-registration-validation") { folder in
                let tx = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("stems"), kind: .stems)
                for name in ["", ".", "..", "../escape.wav", "a/b.wav", "a\\b.wav", "a:b.wav", "a\0b.wav", "a\nb.wav", String(repeating: "x", count: 256)] {
                    try rejects("bad leaf " + name.debugDescription) { _ = try tx.register(filename: name) }
                }
                _ = try tx.register(filename: "Kick.wav")
                try rejects("case-equivalent duplicate") { _ = try tx.register(filename: "kick.wav") }
                _ = try tx.register(filename: "Café.wav")
                try rejects("unicode-equivalent duplicate") { _ = try tx.register(filename: "Cafe\u{301}.wav") }
                try tx.discard()
                let one = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("one.wav"), kind: .file)
                _ = try one.register(filename: "first.wav")
                try rejects("second file entry") { _ = try one.register(filename: "second.wav") }
                try one.discard()
                let empty = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("empty.wav"), kind: .file)
                try rejects("empty transaction") { _ = try empty.publish() }; try empty.discard()
            }
            try test("symlinks-never-followed") { folder in
                let outside = try directory(folder, "outside")
                let keep = outside.appendingPathComponent("keep.wav"); try bytes("protected", to: keep)
                let linkedFile = folder.appendingPathComponent("file-link.wav")
                try fm.createSymbolicLink(at: linkedFile, withDestinationURL: keep)
                try rejects("target symlink") { _ = try AudioExportTransaction(destinationURL: linkedFile, kind: .file) }
                let linkedParent = folder.appendingPathComponent("parent-link")
                try fm.createSymbolicLink(at: linkedParent, withDestinationURL: outside)
                try rejects("parent symlink") { _ = try AudioExportTransaction(destinationURL: linkedParent.appendingPathComponent("new.wav"), kind: .file) }
                let tx = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("safe.wav"), kind: .file)
                let entry = try tx.register(filename: "one.wav")
                try fm.createSymbolicLink(at: entry.destinationURL, withDestinationURL: keep)
                try fm.createSymbolicLink(at: entry.sourceURL, withDestinationURL: outside)
                try rejects("delivery symlink") { _ = try tx.publish() }
                try tx.discard(); try stagingGone(tx)
                try require(content(keep) == "protected", "Cleanup followed private symlink")
            }
            try test("staging-identity-and-extra-files") { folder in
                let tx = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("out.wav"), kind: .file)
                let entry = try tx.register(filename: "one.wav"); try bytes("ready", to: entry.destinationURL)
                let extra = tx.deliveryDirectoryURL.appendingPathComponent("unexpected.wav")
                try bytes("unexpected", to: extra)
                try rejects("unregistered output") { _ = try tx.publish() }
                try fm.removeItem(at: extra)
                let ownRoot = tx.sourcesDirectoryURL.deletingLastPathComponent()
                let movedRoot = folder.appendingPathComponent("moved-private")
                try fm.moveItem(at: ownRoot, to: movedRoot)
                let outsider = try directory(folder, "outsider")
                try bytes("keep", to: outsider.appendingPathComponent("keep.txt"))
                try fm.createSymbolicLink(at: ownRoot, withDestinationURL: outsider)
                try rejects("private root replaced") { _ = try tx.publish() }
                try rejects("cleanup foreign root") { try tx.discard() }
                try require(content(outsider.appendingPathComponent("keep.txt")) == "keep", "Cleanup touched replacement root")
                try fm.removeItem(at: ownRoot)
                try fm.moveItem(at: movedRoot, to: ownRoot)
                try tx.discard(); try stagingGone(tx)
            }
            try test("parent-identity-and-abandoned-cleanup") { folder in
                let parent = try directory(folder, "parent")
                let tx = try AudioExportTransaction(destinationURL: parent.appendingPathComponent("out.wav"), kind: .file)
                let entry = try tx.register(filename: "one.wav"); try bytes("ready", to: entry.destinationURL)
                let moved = folder.appendingPathComponent("moved-parent")
                try fm.moveItem(at: parent, to: moved)
                _ = try directory(folder, "parent")
                try bytes("new-owner", to: parent.appendingPathComponent("out.wav"))
                try rejects("parent object replaced") { _ = try tx.publish() }
                try tx.discard()
                try require(content(parent.appendingPathComponent("out.wav")) == "new-owner", "New parent changed")
                try require(fm.contentsOfDirectory(atPath: moved.path).isEmpty, "FD-owned cleanup missed moved original parent")
                var abandoned: AudioExportTransaction? = try AudioExportTransaction(destinationURL: folder.appendingPathComponent("abandoned.wav"), kind: .file)
                let privateRoot = abandoned!.sourcesDirectoryURL.deletingLastPathComponent()
                let abandonedEntry = try abandoned!.register(filename: "one.wav")
                try bytes("temporary", to: abandonedEntry.sourceURL)
                abandoned = nil
                try require(!fm.fileExists(atPath: privateRoot.path), "Deinit left private files")
                try require(!fm.fileExists(atPath: folder.appendingPathComponent("abandoned.wav").path), "Abandonment published a file")
            }
            try report()
            print("AudioExportTransaction: \(checks.count) groups passed")
        } catch {
            try? report(error: String(describing: error))
            throw error
        }
    }
}
